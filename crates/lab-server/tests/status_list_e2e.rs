/// `lst` of two concatenated ZLIB streams: `first`, then `second` (both 1-bit lists).
fn two_streams(first: &[u8], second: &[u8]) -> String {
    let decode = |lst: String| URL_SAFE_NO_PAD.decode(lst).expect("base64url");
    let mut bytes = decode(encode_lst(first, ONE_BIT));
    bytes.extend(decode(encode_lst(second, ONE_BIT)));
    URL_SAFE_NO_PAD.encode(bytes)
}

/// The standard base64 DER of the first certificate in `pem` (an `x5c` entry).
fn pem_b64(pem: &[u8]) -> String {
    std::str::from_utf8(pem)
        .expect("PEM is ASCII")
        .lines()
        .skip_while(|line| !line.starts_with("-----BEGIN"))
        .skip(1)
        .take_while(|line| !line.starts_with("-----END"))
        .collect()
}

fn now_secs() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("clock after epoch")
        .as_secs()
}

/// `statuses` as a list of `LIST_ENTRIES` entries, `value` at `IDX`, `VALID` elsewhere.
fn list_with(value: u8) -> Vec<u8> {
    let mut statuses = vec![VALID; LIST_ENTRIES];
    statuses[usize::try_from(IDX).expect("small index")] = value;
    statuses
}

/// Honest claims for `uri`: `iat` now, `exp` in an hour, `statuses` at `bits`.
fn claims(uri: &str, statuses: &[u8], bits: u8) -> serde_json::Value {
    let now = now_secs();
    status_list_claims(
        uri,
        now,
        Some(now + TOKEN_LIFETIME_SECS),
        bits,
        &encode_lst(statuses, bits),
    )
}

/// The suite's signer: the credential issuer's own key (README §5a).
fn issuer_signer() -> StatusListSigner {
    StatusListSigner::from_jwk(ISSUER_JWK).expect("issuer key signs lists")
}

fn pinned_issuer_key() -> StatusListTrust {
    StatusListTrust::pinned_key(ISSUER_PUBLIC_JWK).expect("pinned key")
}

fn status_ca() -> StatusListTrust {
    StatusListTrust::x509_from_pem(STATUS_CA_PEM).expect("status CA")
}

/// A conformance server as the OIDF run configures it (`x509_san_dns`, the PID query), with
/// `status_list` as its status policy.
fn config(status_list: Option<StatusListPolicy>) -> LabConfig {
    let mut config = LabConfig::new(
        Mode::Conformance,
        RequestSigningKey::from_jwk(LEAF_JWK).expect("leaf signing key"),
        TrustedIssuerKey::from_jwk(ISSUER_PUBLIC_JWK).expect("issuer key"),
    );
    config.client_id =
        protocol_model::ClientIdWire::new(format!("x509_san_dns:{PUBLIC_HOST}")).expect("id");
    config.credential_request =
        CredentialRequest::new(PID_QUERY_ID, PID_VCT, PID_CLAIMS).expect("PID query");
    let mut conformance = ConformanceConfig::new(
        X509Credentials::from_pem(LEAF_PEM, LEAF_KEY_PEM, CA_PEM).expect("fixture credentials"),
        PublicOrigin::parse(PUBLIC_ORIGIN).expect("origin"),
    );
    conformance.status_list = status_list;
    config.conformance = Some(conformance);
    config
}

fn issuer(status_uri: Option<&str>, idx: u64) -> SyntheticIssuer {
    let issuer = SyntheticIssuer::from_jwk(ISSUER_JWK)
        .expect("fixture issuer")
        .with_vct(PID_VCT);
    match status_uri {
        Some(uri) => issuer.with_status_list(uri, idx),
        None => issuer,
    }
}

struct Lab {
    server: LabServer,
    wallet: WalletSim,
}

impl Lab {
    /// A conformance server with `policy`; the wallet holds one credential from `issuer`.
    async fn start(policy: Option<StatusListPolicy>, issuer: &SyntheticIssuer) -> Self {
        let server = LabServer::start(config(policy))
            .await
            .expect("conformance server starts");
        let wallet = WalletSim::with_x509_trust(CA_PEM, PUBLIC_HOST, server.local_addr(), issuer)
            .expect("wallet builds");
        Self { server, wallet }
    }

    /// A policy for `provider` that pins its TLS certificate (the conformance leaf).
    fn policy(provider: &StatusProvider, trust: StatusListTrust) -> StatusListPolicy {
        StatusListPolicy::new(provider.prefix(), trust, LEAF_PEM).expect("status policy")
    }

    async fn session(&self) -> CreatedSession {
        self.wallet
            .create_session(&self.server.base_url(), RouteKind::Unique, None)
            .await
            .expect("session is created")
    }

    /// An honest response to a fresh session; the session, HTTP status and body, and the one
    /// evidence record.
    async fn respond(&self) -> (CreatedSession, u16, Vec<u8>, EvidenceRecord) {
        let session = self.session().await;
        let request = self
            .wallet
            .fetch_request(&session)
            .await
            .expect("request object verifies");
        let jwe = self
            .wallet
            .seal_ecdh_es(
                &request,
                ContentEncryption::A128Gcm,
                &SealOptions::default(),
            )
            .expect("wallet seals");
        let reply = self
            .wallet
            .post_response(&request.response_uri, &jwe)
            .await
            .expect("response endpoint answers");
        let mut records = self.server.evidence().take();
        assert_eq!(records.len(), 1, "exactly one evidence record: {records:?}");
        (session, reply.status, reply.body, records.remove(0))
    }

    async fn state(&self, session: &CreatedSession) -> String {
        self.wallet
            .session_state(&session.result_uri)
            .await
            .expect("result endpoint answers")
            .expect("session known")
    }

    /// The response was refused at the status step with `want`: generic 400, holder binding
    /// had passed, nothing was claimed, the session stays pending.
    async fn assert_status_refused(&self, want: StatusError) {
        let (session, status, body, record) = self.respond().await;
        assert_eq!(
            (status, body.as_slice()),
            (BAD_REQUEST, GENERIC_REJECTION_BODY.as_bytes()),
            "{want:?}"
        );
        assert!(
            matches!(
                record.validation_result,
                lab_server::ValidationResult::Passed { validated: 1 }
            ),
            "{want:?}: {record:?}"
        );
        assert_eq!(record.status_result, StatusResult::Failed(want));
        assert_eq!(record.rejection, Some(Rejection::Status(want)));
        assert_eq!(record.commit_result, CommitResult::NotRun);
        assert_eq!(record.committed_session, None);
        assert_eq!(self.state(&session).await, "pending", "{want:?}");
    }
}

async fn provider() -> StatusProvider {
    StatusProvider::start(LEAF_PEM, LEAF_KEY_PEM)
        .await
        .expect("status provider starts")
}

/// The decisive case: one credential, one list. While the list holds `0x00` at the
/// credential's index the presentation commits; after only the list changes that entry to
/// `0x01`, a presentation of the very same credential is refused as revoked. Each response
/// caused exactly one GET of the list, with the TSL §8.1 `Accept` header.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn same_credential_flips_from_accepted_to_revoked_when_only_the_list_changes() {
    let provider = provider().await;
    let uri = provider.uri(LIST_ID);
    let lab = Lab::start(
        Some(Lab::policy(&provider, pinned_issuer_key())),
        &issuer(Some(&uri), IDX),
    )
    .await;
    let signer = issuer_signer();

    provider.set_reply(StatusReply::token(&signer.token(&claims(
        &uri,
        &list_with(VALID),
        ONE_BIT,
    ))));
    let (accepted, status, body, record) = lab.respond().await;
    assert_eq!((status, body.as_slice()), (OK, b"{}".as_slice()));
    assert_eq!(record.status_result, StatusResult::Valid);
    assert_eq!(record.rejection, None);
    assert_eq!(record.commit_result, CommitResult::Committed);
    assert_eq!(lab.state(&accepted).await, "consumed");

    provider.set_reply(StatusReply::token(&signer.token(&claims(
        &uri,
        &list_with(INVALID),
        ONE_BIT,
    ))));
    lab.assert_status_refused(StatusError::Revoked).await;

    let requests = provider.requests();
    assert_eq!(requests.len(), 2, "one fetch per response: {requests:?}");
    for request in requests {
        assert_eq!(request.method, "GET");
        assert_eq!(request.path, format!("/statuslists/{LIST_ID}"));
        assert_eq!(request.query, None);
        assert_eq!(request.accept.as_deref(), Some(STATUS_LIST_JWT_MEDIA_TYPE));
    }
}

/// A credential without a `status` claim (the suite's `present-credential-without-status`)
/// is accepted on a server with a status policy, and nothing is fetched.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn credential_without_status_is_accepted_without_a_fetch() {
    let provider = provider().await;
    let lab = Lab::start(
        Some(Lab::policy(&provider, pinned_issuer_key())),
        &issuer(None, IDX),
    )
    .await;
    let (session, status, _, record) = lab.respond().await;
    assert_eq!(status, OK);
    assert_eq!(record.status_result, StatusResult::NotReferenced);
    assert_eq!(lab.state(&session).await, "consumed");
    assert!(provider.requests().is_empty());
}

/// Every token- and list-level reason the status cannot be established, and the non-VALID
/// values, each refused with its own variant (never `Revoked` unless the value is `0x01`).
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn token_and_list_failures_are_refused_and_recorded_apart_from_revocation() {
    let provider = provider().await;
    let uri = provider.uri(LIST_ID);
    let lab = Lab::start(
        Some(Lab::policy(&provider, pinned_issuer_key())),
        &issuer(Some(&uri), IDX),
    )
    .await;
    let signer = issuer_signer();
    let now = now_secs();
    let lst = encode_lst(&list_with(VALID), ONE_BIT);
    let with = |patch: serde_json::Value| {
        let mut claims = claims(&uri, &list_with(VALID), ONE_BIT);
        for (name, value) in patch.as_object().expect("patch object") {
            if value.is_null() {
                claims.as_object_mut().expect("claims").remove(name);
            } else {
                claims[name] = value.clone();
            }
        }
        claims
    };
    let other_key = StatusListSigner::generate().expect("other key");
    let header = |members: serde_json::Value| -> Map<String, serde_json::Value> {
        members.as_object().cloned().expect("header object")
    };
    let cases: Vec<(String, StatusError)> = vec![
        (
            signer.token(&claims(&uri, &list_with(SUSPENDED), TWO_BITS)),
            StatusError::Suspended,
        ),
        (
            signer.token(&claims(&uri, &list_with(APPLICATION_SPECIFIC), TWO_BITS)),
            StatusError::NotValid(APPLICATION_SPECIFIC),
        ),
        (
            signer.token(&with(json!({ "exp": now - 1 }))),
            StatusError::TokenExpired,
        ),
        (
            signer.token(&with(json!({ "iat": now + FAR_SECS }))),
            StatusError::TokenNotYetValid,
        ),
        (
            signer.token(&with(json!({ "nbf": now + FAR_SECS }))),
            StatusError::TokenNotYetValid,
        ),
        (
            signer.token(&with(json!({ "sub": provider.uri("2") }))),
            StatusError::SubjectMismatch,
        ),
        (
            signer.token(&with(json!({ "iat": null }))),
            StatusError::TokenMalformed,
        ),
        (
            signer.token(&with(json!({ "iat": 1.5 }))),
            StatusError::TokenMalformed,
        ),
        (
            signer.token(&with(json!({ "ttl": 0 }))),
            StatusError::TokenMalformed,
        ),
        (
            signer.token(&with(json!({ "status_list": null }))),
            StatusError::TokenMalformed,
        ),
        (
            signer.token(&with(json!({ "status_list": { "bits": 3, "lst": lst } }))),
            StatusError::ListMalformed,
        ),
        (
            signer.token(&with(
                json!({ "status_list": { "bits": 1, "lst": "bm90LXpsaWI" } }),
            )),
            StatusError::ListMalformed,
        ),
        (
            signer.token(&with(
                json!({ "status_list": { "bits": 1, "lst": "not base64url!" } }),
            )),
            StatusError::ListMalformed,
        ),
        (
            signer.sign(&header(json!({ "typ": "jwt" })), &with(json!({}))),
            StatusError::TokenTyp,
        ),
        (
            signer.sign(&header(json!({ "alg": "ES384" })), &with(json!({}))),
            StatusError::TokenAlg,
        ),
        (
            signer.sign(&header(json!({ "crit": ["x"] })), &with(json!({}))),
            StatusError::TokenMalformed,
        ),
        // Another key, announcing its complete public JWK in `jwk`: the pinned key alone is
        // trusted.
        (
            other_key.sign(
                &header(json!({ "jwk": other_key.public_jwk() })),
                &with(json!({})),
            ),
            StatusError::TokenSignature,
        ),
        // RFC 7519 §4.1.3: an `aud` that does not name the lab (it has no identifier).
        (
            signer.token(&with(json!({ "aud": "https://another-verifier.lab.invalid" }))),
            StatusError::TokenAudience,
        ),
        // A VALID stream followed by a second one that marks the index INVALID.
        (
            signer.token(&with(json!({
                "status_list": { "bits": 1, "lst": two_streams(&list_with(VALID), &list_with(INVALID)) }
            }))),
            StatusError::ListMalformed,
        ),
        ("not-a-jws".to_owned(), StatusError::TokenMalformed),
    ];
    for (token, want) in cases {
        provider.set_reply(StatusReply::token(&token));
        lab.assert_status_refused(want).await;
    }

    // A list shorter than the credential's index (TSL §8.3 step 6).
    provider.set_reply(StatusReply::token(&signer.token(&claims(
        &uri,
        &[VALID; 4],
        ONE_BIT,
    ))));
    let short = Lab::start(
        Some(Lab::policy(&provider, pinned_issuer_key())),
        &issuer(Some(&uri), u64::try_from(LIST_ENTRIES).expect("small")),
    )
    .await;
    short
        .assert_status_refused(StatusError::IndexOutOfRange)
        .await;
}

/// How the fetch itself can fail: answers other than a `200` Status List Token response, a
/// redirect (not followed), a body over the bound, a TLS certificate other than the pinned
/// one, nobody listening, a provider that never answers, and a host that is not loopback.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn fetch_failures_are_refused_and_recorded_apart_from_revocation() {
    let provider = provider().await;
    let uri = provider.uri(LIST_ID);
    let lab = Lab::start(
        Some(Lab::policy(&provider, pinned_issuer_key())),
        &issuer(Some(&uri), IDX),
    )
    .await;
    let token = issuer_signer().token(&claims(&uri, &list_with(VALID), ONE_BIT));
    let reply = |status: u16, headers: &[(&str, &str)], body: &[u8]| StatusReply {
        status,
        headers: headers
            .iter()
            .map(|(n, v)| ((*n).to_owned(), (*v).to_owned()))
            .collect(),
        body: body.to_vec(),
        stall_body: false,
    };
    let jwt_type = ("content-type", STATUS_LIST_JWT_MEDIA_TYPE);
    let cases = [
        (reply(NOT_FOUND, &[], b""), FetchFailure::Status(NOT_FOUND)),
        (
            reply(FOUND, &[("location", "https://localhost:1/elsewhere")], b""),
            FetchFailure::Status(FOUND),
        ),
        (
            reply(
                OK,
                &[("content-type", "application/json")],
                token.as_bytes(),
            ),
            FetchFailure::ContentType,
        ),
        (reply(OK, &[], token.as_bytes()), FetchFailure::ContentType),
        (
            reply(
                OK,
                &[jwt_type, ("content-encoding", "gzip")],
                token.as_bytes(),
            ),
            FetchFailure::ContentEncoding,
        ),
        (
            reply(
                OK,
                &[jwt_type],
                &vec![b'a'; MAX_STATUS_LIST_TOKEN_BYTES + 1],
            ),
            FetchFailure::Body,
        ),
    ];
    for (reply, want) in cases {
        provider.set_reply(reply);
        lab.assert_status_refused(StatusError::Fetch(want)).await;
    }

    // Headers, then a body that never comes: the fetch deadline fires mid-response, and the
    // HTTP connection task is dropped with the check.
    provider.set_reply(StatusReply {
        stall_body: true,
        ..reply(OK, &[jwt_type, ("content-length", "4096")], b"")
    });
    let started = Instant::now();
    lab.assert_status_refused(StatusError::Fetch(FetchFailure::Timeout))
        .await;
    let waited = started.elapsed();
    assert!(
        waited >= STATUS_LIST_FETCH_TIMEOUT && waited < STATUS_LIST_FETCH_TIMEOUT + TIMEOUT_SLACK,
        "{waited:?}"
    );

    // The Status Provider presents another certificate than the pinned one.
    let wrong_pin =
        StatusListPolicy::new(provider.prefix(), pinned_issuer_key(), WILDCARD_LEAF_PEM)
            .expect("policy");
    provider.set_reply(StatusReply::token(&token));
    Lab::start(Some(wrong_pin), &issuer(Some(&uri), IDX))
        .await
        .assert_status_refused(StatusError::Fetch(FetchFailure::Tls))
        .await;

    // Nobody listens any more.
    let prefix = provider.prefix();
    drop(provider);
    let gone = StatusListPolicy::new(prefix, pinned_issuer_key(), LEAF_PEM).expect("policy");
    Lab::start(Some(gone), &issuer(Some(&uri), IDX))
        .await
        .assert_status_refused(StatusError::Fetch(FetchFailure::Connect))
        .await;

    // A provider that accepts the connection and never answers: the fetch deadline fires.
    let stalled = TcpListener::bind((Ipv4Addr::LOCALHOST, 0))
        .await
        .expect("bind");
    let port = stalled.local_addr().expect("addr").port();
    let hold = tokio::spawn(async move {
        let mut held = Vec::new();
        while let Ok((stream, _)) = stalled.accept().await {
            held.push(stream);
        }
    });
    let stalled_prefix = format!("https://localhost:{port}/statuslists/");
    let stalled_uri = format!("{stalled_prefix}{LIST_ID}");
    let policy =
        StatusListPolicy::new(stalled_prefix, pinned_issuer_key(), LEAF_PEM).expect("policy");
    let lab = Lab::start(Some(policy), &issuer(Some(&stalled_uri), IDX)).await;
    let started = Instant::now();
    lab.assert_status_refused(StatusError::Fetch(FetchFailure::Timeout))
        .await;
    let waited = started.elapsed();
    assert!(
        waited >= STATUS_LIST_FETCH_TIMEOUT && waited < STATUS_LIST_FETCH_TIMEOUT + TIMEOUT_SLACK,
        "{waited:?}"
    );
    hold.abort();

    // An allowed prefix whose host is not loopback: refused before any connection.
    let remote_prefix = format!("https://{TEST_NET_HOST}/statuslists/");
    let remote_uri = format!("{remote_prefix}{LIST_ID}");
    let policy =
        StatusListPolicy::new(remote_prefix, pinned_issuer_key(), LEAF_PEM).expect("policy");
    Lab::start(Some(policy), &issuer(Some(&remote_uri), IDX))
        .await
        .assert_status_refused(StatusError::Fetch(FetchFailure::NotLoopback))
        .await;
}

