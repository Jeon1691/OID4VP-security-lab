/// HAIP-style trust (TSL §11.3): the token's `x5c` must chain to the separate status CA. A
/// signer certificate from that CA is accepted; the suite's shape (a self-signed `x5c`), a
/// certificate from the Verifier's own CA, the anchor inside `x5c`, no `x5c` at all, and a
/// signature by a key other than the leaf's are not.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn x509_trust_accepts_only_a_signer_certified_by_the_status_ca() {
    let provider = provider().await;
    let uri = provider.uri(LIST_ID);
    let lab = Lab::start(
        Some(Lab::policy(&provider, status_ca())),
        &issuer(Some(&uri), IDX),
    )
    .await;
    let valid = claims(&uri, &list_with(VALID), ONE_BIT);
    let signer = StatusListSigner::from_jwk(STATUS_SIGNER_JWK).expect("status signer");

    let certified = signer
        .with_x5c_pem(STATUS_SIGNER_PEM)
        .expect("x5c")
        .token(&valid);
    provider.set_reply(StatusReply::token(&certified));
    let (session, status, _, record) = lab.respond().await;
    assert_eq!(status, OK);
    assert_eq!(record.status_result, StatusResult::Valid);
    assert_eq!(lab.state(&session).await, "consumed");

    // Revocation is still read from the list under this trust mode.
    let revoked = StatusListSigner::from_jwk(STATUS_SIGNER_JWK)
        .and_then(|s| s.with_x5c_pem(STATUS_SIGNER_PEM))
        .expect("signer")
        .token(&claims(&uri, &list_with(INVALID), ONE_BIT));
    provider.set_reply(StatusReply::token(&revoked));
    lab.assert_status_refused(StatusError::Revoked).await;

    let signer_chain = [STATUS_SIGNER_PEM, STATUS_CA_PEM].concat();
    let cases = [
        // Issued by the status CA, but with an extended key usage (serverAuth).
        (
            STATUS_SIGNER_JWK,
            Some(STATUS_SIGNER_EKU_PEM.to_vec()),
            StatusError::UntrustedSigner,
        ),
        // The OIDF suite's shape: a self-signed certificate in `x5c`.
        (
            STATUS_SIGNER_JWK,
            Some(FOREIGN_CA_PEM.to_vec()),
            StatusError::UntrustedSigner,
        ),
        // A leaf of the Verifier's own CA (serverAuth), signing with its own key.
        (
            LEAF_JWK,
            Some(LEAF_PEM.to_vec()),
            StatusError::UntrustedSigner,
        ),
        // The trust anchor must not travel in `x5c`.
        (
            STATUS_SIGNER_JWK,
            Some(signer_chain),
            StatusError::UntrustedSigner,
        ),
        (STATUS_SIGNER_JWK, None, StatusError::UntrustedSigner),
        // The certified leaf, but signed by another key.
        (
            ISSUER_JWK,
            Some(STATUS_SIGNER_PEM.to_vec()),
            StatusError::TokenSignature,
        ),
    ];
    for (key, x5c, want) in cases {
        let mut signer = StatusListSigner::from_jwk(key).expect("signer");
        if let Some(pem) = x5c {
            signer = signer.with_x5c_pem(&pem).expect("x5c");
        }
        provider.set_reply(StatusReply::token(&signer.token(&valid)));
        lab.assert_status_refused(want).await;
    }

    // A certified leaf followed by an entry that is base64 but no certificate: every `x5c`
    // entry must parse, used on the path or not.
    let signer = StatusListSigner::from_jwk(STATUS_SIGNER_JWK).expect("status signer");
    let x5c = json!([pem_b64(STATUS_SIGNER_PEM), "bm90LWEtY2VydGlmaWNhdGU="]);
    let header = json!({ "x5c": x5c }).as_object().cloned().expect("header");
    provider.set_reply(StatusReply::token(&signer.sign(&header, &valid)));
    lab.assert_status_refused(StatusError::UntrustedSigner)
        .await;
}

/// Fail closed without a policy: a conformance server configured without one, and a hardened
/// server (no status code at all), refuse a credential that references a status list, after
/// it validated; and a malformed `status` claim is a validation failure.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn without_a_status_policy_a_referenced_status_is_refused() {
    let uri = "https://localhost:1/statuslists/1";
    Lab::start(None, &issuer(Some(uri), IDX))
        .await
        .assert_status_refused(StatusError::NoPolicy)
        .await;

    let mut hardened = LabConfig::new(
        Mode::Hardened,
        RequestSigningKey::from_jwk(SPRUCE_JWK).expect("did:key signing key"),
        TrustedIssuerKey::from_jwk(ISSUER_PUBLIC_JWK).expect("issuer key"),
    );
    hardened.bind = SocketAddr::from((Ipv4Addr::LOCALHOST, 0));
    let server = LabServer::start(hardened).await.expect("hardened starts");
    let issuer = SyntheticIssuer::from_jwk(ISSUER_JWK)
        .expect("issuer")
        .with_status_list(uri, IDX);
    let wallet = WalletSim::new(&issuer).expect("wallet");
    let session = wallet
        .create_session(&server.base_url(), RouteKind::Unique, None)
        .await
        .expect("session");
    let request = wallet.fetch_request(&session).await.expect("request");
    let jwe = wallet
        .seal(&request, &SealOptions::default())
        .expect("seal");
    let reply = wallet
        .post_response(&request.response_uri, &jwe)
        .await
        .expect("answer");
    assert_eq!(reply.status, BAD_REQUEST);
    let record = server.evidence().take().remove(0);
    assert_eq!(
        record.status_result,
        StatusResult::Failed(StatusError::NoPolicy)
    );
    assert_eq!(
        record.rejection,
        Some(Rejection::Status(StatusError::NoPolicy))
    );
    assert_eq!(
        wallet
            .session_state(&session.result_uri)
            .await
            .expect("result")
            .as_deref(),
        Some("pending")
    );

    // An empty `uri` is no reference at all: refused while validating, nothing to check.
    let provider = provider().await;
    let lab = Lab::start(
        Some(Lab::policy(&provider, pinned_issuer_key())),
        &SyntheticIssuer::from_jwk(ISSUER_JWK)
            .expect("issuer")
            .with_vct(PID_VCT)
            .with_status_list("", IDX),
    )
    .await;
    let (session, status, _, record) = lab.respond().await;
    assert_eq!(status, BAD_REQUEST);
    assert_eq!(
        record.rejection,
        Some(Rejection::Validation(ValidationError::StatusClaimMalformed))
    );
    assert_eq!(record.status_result, StatusResult::NotRun);
    assert_eq!(lab.state(&session).await, "pending");
    assert!(provider.requests().is_empty());
}

/// A status policy needs a request timeout of at least the fetch deadline plus its margin;
/// otherwise the request could time out (408, no evidence) before the status check records its
/// own failure.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn status_policy_needs_a_request_timeout_above_the_fetch_deadline() {
    let provider = provider().await;
    let needed = STATUS_LIST_FETCH_TIMEOUT + STATUS_CHECK_TIMEOUT_MARGIN;
    for short in [STATUS_LIST_FETCH_TIMEOUT, needed - Duration::from_millis(1)] {
        let mut config = config(Some(Lab::policy(&provider, pinned_issuer_key())));
        config.request_timeout = short;
        assert!(
            matches!(
                LabServer::start(config).await,
                Err(lab_server::StartError::StatusFetchTimeout)
            ),
            "{short:?}"
        );
    }
    let mut config = config(Some(Lab::policy(&provider, pinned_issuer_key())));
    config.request_timeout = needed;
    assert!(LabServer::start(config).await.is_ok());
}
