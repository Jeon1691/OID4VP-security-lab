//! Token Status List checking (draft-ietf-oauth-status-list-14, "TSL"; module
//! `status_list`, docs/adr/0003-status-list-checking.md) end to end: a conformance server with
//! a status policy, the wallet simulator presenting a credential that references a list, and a
//! loopback HTTPS Status Provider (`status_sim`) serving Status List Tokens and recording every
//! request.
//!
//! Spec text these tests exercise:
//! - TSL §8.3: the Referenced Token is validated first; then the Status List Token is
//!   resolved from `uri`, validated (§5.1: `typ` `statuslist+jwt`, `sub` = `uri`, `iat`, `exp`,
//!   a valid signature), decompressed, and the value at `idx` read; out of range, "no statement
//!   ... can be made" and the token is rejected. §7.1: `0x00` VALID, `0x01` INVALID, `0x02`
//!   SUSPENDED. §8.1: a GET with `Accept: application/statuslist+jwt`. §8.2: `Content-Type`
//!   `application/statuslist+jwt`. §11.3: the list signer is a pinned key or certified by a CA.
//!
//! Invariants under test: the status is checked only after the credential validated and
//! before the session commits; the same credential is accepted while its list entry is `0x00`
//! and refused once only the list changes it to `0x01`, with a real fetch each time; every way
//! the status cannot be established (fetch, TLS, signature, trust chain, expiry, subject,
//! range, shape) refuses the response with its own `StatusError`, distinct from revocation,
//! and leaves the session pending; a credential without a status claim is accepted without a
//! fetch; without a status policy, a credential that references one is refused (fail closed).
//!
//! All keys, certificates, credentials and lists are synthetic (tests/fixtures, generated by
//! scripts/conformance_fixtures.py).

