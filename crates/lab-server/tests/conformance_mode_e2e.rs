//! Conformance mode (`conformance` feature, `Mode::Conformance`;
//! docs/adr/0002-conformance-mode.md) over real HTTPS on loopback, with the wallet simulator
//! as the Wallet: TLS verified against the synthetic CA, the `x5c` leaf verified to chain to it
//! and to match the `x509_san_dns` / `x509_hash` client id, ECDH-ES sealing with `A128GCM` and
//! `A256GCM`.
//!
//! Spec text these tests exercise:
//! - OpenID4VP 1.0 Final §5.9.3: `x509_san_dns` "MUST be a DNS name and match a dNSName
//!   Subject Alternative Name (SAN)"; `x509_hash` is "the base64url-encoded value of the
//!   SHA-256 hash of the DER-encoded X.509 certificate"; for both the request "MUST be signed
//!   with the private key corresponding to the public key in the leaf X.509 certificate" sent
//!   in `x5c`, and the Wallet "MUST validate the signature and the trust chain".
//! - OpenID4VP 1.0 Final §5.1 / §11.1 / B.3.4 (`client_metadata`: `jwks`, `vp_formats_supported`,
//!   `encrypted_response_enc_values_supported`), §5.8 (`aud`), §8.2 (`response_uri` answers 200
//!   JSON, optionally `redirect_uri`), §8.3 (the JWE `alg` is the JWK's, the JWE carries its
//!   `kid`), B.3.6 (KB-JWT `aud` is the Client Identifier, prefix included).
//! - HAIP 1.0 §5: `x509_hash`; the trust anchor "MUST NOT be included in the x5c"; the signing
//!   certificate "MUST NOT be self-signed"; ECDH-ES P-256 with both `A128GCM` and `A256GCM`
//!   listed; "ephemeral encryption public keys specific to each Authorization Request".
//!
//! Invariants under test: the honest round trip commits for both prefixes and both `enc`
//! values; tampered or misbound responses are refused and consume nothing; the conformance
//! unique route never opens HPKE-0 and the HPKE-0 unique route never opens ECDH-ES; the mode
//! serves no shared or research route; it refuses to start unless its configuration, client id,
//! certificate, key and origin fit, and never binds a non-loopback address; it stops by itself
//! at its maximum runtime; the binary enters it only on the explicit flag.
//!
//! All keys, certificates and credentials are synthetic (tests/fixtures, generated by
//! scripts/conformance_fixtures.py).

