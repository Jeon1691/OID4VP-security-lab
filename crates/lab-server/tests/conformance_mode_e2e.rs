/// HTTP statuses the tests pin (RFC 9110 §15).
const OK: u16 = 200;
const BAD_REQUEST: u16 = 400;
const NOT_FOUND: u16 = 404;
/// Synthetic conformance fixtures (scripts/conformance_fixtures.py).
const CA_PEM: &[u8] = include_bytes!("fixtures/conformance_ca.pem");
const LEAF_PEM: &[u8] = include_bytes!("fixtures/conformance_leaf.pem");
const LEAF_KEY_PEM: &[u8] = include_bytes!("fixtures/conformance_leaf.key.pem");
const LEAF_JWK: &str = include_str!("fixtures/conformance_leaf.jwk");
const MANIFEST: &str = include_str!("fixtures/conformance_fixtures.json");
/// Other synthetic keys: the did:key Request Object key and the lab SD-JWT VC issuer.
const SPRUCE_JWK: &str = include_str!("fixtures/spruce_verifier.jwk");
const ISSUER_JWK: &str = include_str!("fixtures/lab_issuer.jwk");
const ISSUER_PUBLIC_JWK: &str = include_str!("fixtures/lab_issuer.pub.jwk");
/// The public origin the suite container uses (OrbStack forwards it to host loopback); in the
/// tests the client resolves it to the loopback bind.
const PUBLIC_HOST: &str = "host.docker.internal";
const PUBLIC_ORIGIN: &str = "https://host.docker.internal";
/// The OIDF suite's per-test authorization endpoint shape (a synthetic alias).
const SUITE_AUTHORIZATION_ENDPOINT: &str =
    "https://localhost.emobix.co.uk:8443/test/a/lab-synthetic/authorize";
/// The suite's credential type and the top-level PID claims it discloses when asked.
const PID_VCT: &str = "urn:eudi:pid:1";
const PID_QUERY_ID: &str = "pid";
const PID_CLAIMS: [&str; 3] = ["given_name", "family_name", "birthdate"];
/// A response `redirect_uri` (HAIP plan) under the public origin.
const REDIRECT_URI: &str = "https://host.docker.internal/lab/conformance/done";
/// A short maximum runtime for the kill-switch test, and how long it may take to take effect.
const SHORT_RUNTIME: Duration = Duration::from_secs(1);
const RUNTIME_SLACK: Duration = Duration::from_secs(10);
/// JOSE compact segments (RFC 7515 §7.1).
const JWS_HEADER: usize = 0;
const JWS_PAYLOAD: usize = 1;

/// Which x509 Client Identifier Prefix a server uses.
#[derive(Clone, Copy)]
enum Prefix {
    SanDns,
    Hash,
}

fn credentials() -> X509Credentials {
    X509Credentials::from_pem(LEAF_PEM, LEAF_KEY_PEM, CA_PEM).expect("fixture credentials")
}

fn manifest(member: &str) -> String {
    serde_json::from_str::<Value>(MANIFEST).expect("manifest JSON")[member]
        .as_str()
        .expect("manifest member")
        .to_owned()
}

fn client_id(prefix: Prefix) -> protocol_model::ClientIdWire {
    let id = match prefix {
        Prefix::SanDns => manifest("client_id_x509_san_dns"),
        Prefix::Hash => manifest("client_id_x509_hash"),
    };
    protocol_model::ClientIdWire::new(id).expect("client id")
}

/// A conformance server configuration as the OIDF run uses it: the PID query, the fixture
/// credentials under the public origin.
fn config(prefix: Prefix) -> LabConfig {
    let mut config = LabConfig::new(
        Mode::Conformance,
        RequestSigningKey::from_jwk(LEAF_JWK).expect("leaf signing key"),
        TrustedIssuerKey::from_jwk(ISSUER_PUBLIC_JWK).expect("issuer key"),
    );
    config.client_id = client_id(prefix);
    config.credential_request =
        CredentialRequest::new(PID_QUERY_ID, PID_VCT, PID_CLAIMS).expect("PID query");
    config.authorization_endpoint = SUITE_AUTHORIZATION_ENDPOINT.to_owned();
    config.conformance = Some(ConformanceConfig::new(
        credentials(),
        PublicOrigin::parse(PUBLIC_ORIGIN).expect("origin"),
    ));
    config
}

fn issuer() -> SyntheticIssuer {
    SyntheticIssuer::from_jwk(ISSUER_JWK)
        .expect("fixture issuer")
        .with_vct(PID_VCT)
}

struct Lab {
    server: LabServer,
    wallet: WalletSim,
}

impl Lab {
    async fn start(config: LabConfig) -> Self {
        let server = LabServer::start(config)
            .await
            .expect("conformance server starts");
        let wallet =
            WalletSim::with_x509_trust(CA_PEM, PUBLIC_HOST, server.local_addr(), &issuer())
                .expect("wallet builds");
        Self { server, wallet }
    }

    async fn session(&self) -> CreatedSession {
        self.wallet
            .create_session(&self.server.base_url(), RouteKind::Unique, None)
            .await
            .expect("session is created")
    }

    async fn request(&self, session: &CreatedSession) -> RequestObject {
        self.wallet
            .fetch_request(session)
            .await
            .expect("request object verifies against the synthetic CA")
    }

    /// Seals the response for `session` with ECDH-ES and `enc`, POSTs it; status and body.
    async fn respond(
        &self,
        session: &CreatedSession,
        enc: ContentEncryption,
        opts: &SealOptions,
    ) -> (u16, Vec<u8>) {
        let request = self.request(session).await;
        let jwe = self
            .wallet
            .seal_ecdh_es(&request, enc, opts)
            .expect("wallet seals");
        let reply = self
            .wallet
            .post_response(&request.response_uri, &jwe)
            .await
            .expect("response endpoint answers");
        (reply.status, reply.body)
    }

    fn rejection(&self) -> Option<Rejection> {
        let mut records = self.server.evidence().take();
        assert_eq!(records.len(), 1, "exactly one evidence record: {records:?}");
        records.remove(0).rejection
    }

    async fn state(&self, session: &CreatedSession) -> String {
        self.wallet
            .session_state(&session.result_uri)
            .await
            .expect("result endpoint answers")
            .expect("session known")
    }
}

fn decode(segment: &str) -> Map<String, Value> {
    serde_json::from_slice(&URL_SAFE_NO_PAD.decode(segment).expect("base64url"))
        .expect("JSON object")
}

/// The honest round trip with `x509_san_dns` and `A128GCM` (the suite picks the first `enc`),
/// and what the signed Request Object and the session creation response carry.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn conformance_round_trip_over_https_commits_with_x509_san_dns() {
    let lab = Lab::start(config(Prefix::SanDns)).await;
    let base = lab.server.base_url();
    let port = lab.server.local_addr().port();
    assert_eq!(base, format!("{PUBLIC_ORIGIN}:{port}"));
    assert!(lab.server.local_addr().ip().is_loopback());
    let session = lab.session().await;
    assert!(session.request_uri.starts_with(&base));
    assert!(session.response_uri.starts_with(&base));
    let query = form_urlencoded::Serializer::new(String::new())
        .append_pair("client_id", &session.client_id)
        .append_pair("request_uri", &session.request_uri)
        .finish();
    assert_eq!(
        session.authorization_request,
        format!("{SUITE_AUTHORIZATION_ENDPOINT}?{query}")
    );

    let reply = lab.wallet.get(&session.request_uri).await.expect("request");
    let jwt = String::from_utf8(reply.body).expect("compact JWS");
    let segments: Vec<&str> = jwt.split('.').collect();
    let header = decode(segments[JWS_HEADER]);
    let mut header_members: Vec<&str> = header.keys().map(String::as_str).collect();
    header_members.sort_unstable();
    assert_eq!(header_members, ["alg", "typ", "x5c"], "no kid next to x5c");
    assert_eq!(header["typ"], "oauth-authz-req+jwt");
    // x5c = [leaf] only: the trust anchor is never sent (HAIP 1.0 §5).
    let leaf_der = pem_der(LEAF_PEM);
    assert_eq!(
        header["x5c"],
        json!([base64::engine::general_purpose::STANDARD.encode(leaf_der)])
    );
    let payload = decode(segments[JWS_PAYLOAD]);
    assert_eq!(payload["client_id"], "x509_san_dns:host.docker.internal");
    assert_eq!(payload["aud"], "https://self-issued.me/v2");
    assert_eq!(payload["response_mode"], "direct_post.jwt");
    let metadata = payload["client_metadata"]
        .as_object()
        .expect("client_metadata");
    let mut members: Vec<&str> = metadata.keys().map(String::as_str).collect();
    members.sort_unstable();
    assert_eq!(
        members,
        [
            "encrypted_response_enc_values_supported",
            "jwks",
            "vp_formats_supported"
        ]
    );
    assert_eq!(
        metadata["encrypted_response_enc_values_supported"],
        json!(["A128GCM", "A256GCM"])
    );
    assert_eq!(
        metadata["vp_formats_supported"],
        json!({ "dc+sd-jwt": { "sd-jwt_alg_values": ["ES256"], "kb-jwt_alg_values": ["ES256"] } })
    );
    let jwk = &metadata["jwks"]["keys"][0];
    assert_eq!(
        (&jwk["alg"], &jwk["use"], &jwk["crv"]),
        (&json!("ECDH-ES"), &json!("enc"), &json!("P-256"))
    );
    assert!(jwk["kid"].is_string());
    assert_eq!(
        payload["dcql_query"]["credentials"][0]["meta"]["vct_values"],
        json!([PID_VCT])
    );

    let (status, body) = lab
        .respond(
            &session,
            ContentEncryption::A128Gcm,
            &SealOptions::default(),
        )
        .await;
    assert_eq!((status, body.as_slice()), (OK, b"{}".as_slice()));
    assert_eq!(lab.rejection(), None);
    assert_eq!(lab.state(&session).await, "consumed");
}

/// The DER of the first PEM certificate, decoded by hand from the fixture.
fn pem_der(pem: &[u8]) -> Vec<u8> {
    let text = std::str::from_utf8(pem).expect("PEM text");
    let body: String = text
        .lines()
        .filter(|line| !line.starts_with("-----"))
        .collect();
    base64::engine::general_purpose::STANDARD
        .decode(body)
        .expect("PEM base64")
}

/// HAIP shape: `x509_hash`, `A256GCM`, and the configured response `redirect_uri` in the 200
/// answer (OpenID4VP 1.0 §8.2).
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn conformance_round_trip_with_x509_hash_a256gcm_and_redirect_uri() {
    let mut cfg = config(Prefix::Hash);
    if let Some(conformance) = &mut cfg.conformance {
        conformance.response_redirect_uri = Some(REDIRECT_URI.to_owned());
    }
    let lab = Lab::start(cfg).await;
    let session = lab.session().await;
    assert_eq!(session.client_id, manifest("client_id_x509_hash"));
    assert_eq!(
        session.client_id,
        credentials().x509_hash_client_id(),
        "manifest and code agree on the x509_hash value"
    );
    let (status, body) = lab
        .respond(
            &session,
            ContentEncryption::A256Gcm,
            &SealOptions::default(),
        )
        .await;
    assert_eq!(status, OK);
    assert_eq!(
        serde_json::from_slice::<Value>(&body).expect("JSON"),
        json!({ "redirect_uri": REDIRECT_URI })
    );
    assert_eq!(lab.rejection(), None);
    assert_eq!(lab.state(&session).await, "consumed");
    // The same JWE again: the session is consumed.
    let (status, body) = lab
        .respond(
            &session,
            ContentEncryption::A256Gcm,
            &SealOptions::default(),
        )
        .await;
    assert_eq!(
        (status, body.as_slice()),
        (BAD_REQUEST, GENERIC_REJECTION_BODY.as_bytes())
    );
}

/// HAIP 1.0 §5: every session advertises its own ECDH-ES key and `kid`.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn conformance_sessions_get_fresh_encryption_keys() {
    let lab = Lab::start(config(Prefix::Hash)).await;
    let a = lab.request(&lab.session().await).await;
    let b = lab.request(&lab.session().await).await;
    assert_ne!(a.kid, b.kid);
    assert_ne!(a.public_key.to_bytes(), b.public_key.to_bytes());
    assert_ne!(a.nonce, b.nonce);
    assert_ne!(a.state, b.state);
    assert_eq!(
        (a.jwk_alg.as_str(), b.jwk_alg.as_str()),
        ("ECDH-ES", "ECDH-ES")
    );
}

/// Misbound and tampered responses (the suite's negative modules expect a 4xx): wrong KB-JWT
/// `nonce` / `aud`, a corrupted issuer signature, a wrong `state`, a tampered ciphertext and a
/// wrong `kid` are refused with the generic 400 and consume nothing; the honest response then
/// commits.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn conformance_negative_responses_are_refused_and_consume_nothing() {
    let lab = Lab::start(config(Prefix::SanDns)).await;
    let session = lab.session().await;
    let cases = [
        (
            SealOptions {
                presentation: PresentationTamper::KbNonce("another-nonce".to_owned()),
                ..SealOptions::default()
            },
            Rejection::Validation(ValidationError::KbNonceMismatch),
        ),
        (
            SealOptions {
                presentation: PresentationTamper::KbAudience(manifest("client_id_x509_hash")),
                ..SealOptions::default()
            },
            Rejection::Validation(ValidationError::KbAudienceMismatch),
        ),
        (
            SealOptions {
                presentation: PresentationTamper::CorruptIssuerSignature,
                ..SealOptions::default()
            },
            Rejection::Validation(ValidationError::IssuerSignature),
        ),
        (
            SealOptions {
                state: StateChoice::Other(json!("another-state")),
                ..SealOptions::default()
            },
            Rejection::Validation(ValidationError::StateMismatch),
        ),
        (
            SealOptions {
                tamper_ciphertext: true,
                ..SealOptions::default()
            },
            Rejection::Decrypt,
        ),
        (
            SealOptions {
                kid: KidChoice::Other("not-this-sessions-kid".to_owned()),
                ..SealOptions::default()
            },
            Rejection::Resolve(session_core::ResolveError::NoCandidate),
        ),
    ];
    for (opts, want) in cases {
        let (status, body) = lab
            .respond(&session, ContentEncryption::A128Gcm, &opts)
            .await;
        assert_eq!(
            (status, body.as_slice()),
            (BAD_REQUEST, GENERIC_REJECTION_BODY.as_bytes()),
            "{want:?}"
        );
        assert_eq!(lab.rejection(), Some(want));
        assert_eq!(lab.state(&session).await, "pending");
    }
    let (status, _) = lab
        .respond(
            &session,
            ContentEncryption::A128Gcm,
            &SealOptions::default(),
        )
        .await;
    assert_eq!(status, OK);
    assert_eq!(lab.rejection(), None);
}

/// No downgrade either way: an HPKE-0 JWE to the conformance unique route is refused at parse
/// (`EcdhEsJweParse`), and an ECDH-ES JWE to a hardened server's HPKE-0 unique route is refused
/// at parse (`JweParse`); both sessions stay pending.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn conformance_route_refuses_hpke_and_hpke_route_refuses_ecdh_es() {
    let lab = Lab::start(config(Prefix::SanDns)).await;
    let session = lab.session().await;
    let request = lab.request(&session).await;
    let hpke = lab
        .wallet
        .seal(&request, &SealOptions::default())
        .expect("HPKE-0 seal to the advertised P-256 key");
    let reply = lab
        .wallet
        .post_response(&request.response_uri, &hpke)
        .await
        .expect("answer");
    assert_eq!(reply.status, BAD_REQUEST);
    assert!(matches!(
        lab.rejection(),
        Some(Rejection::EcdhEsJweParse(_))
    ));
    assert_eq!(lab.state(&session).await, "pending");

    let hardened = LabServer::start(LabConfig::new(
        Mode::Hardened,
        RequestSigningKey::from_jwk(SPRUCE_JWK).expect("key"),
        TrustedIssuerKey::from_jwk(ISSUER_PUBLIC_JWK).expect("issuer key"),
    ))
    .await
    .expect("hardened server");
    let wallet =
        WalletSim::new(&SyntheticIssuer::from_jwk(ISSUER_JWK).expect("issuer")).expect("wallet");
    let session = wallet
        .create_session(&hardened.base_url(), RouteKind::Unique, None)
        .await
        .expect("session");
    let request = wallet.fetch_request(&session).await.expect("request");
    assert_eq!(request.jwk_alg, "HPKE-0");
    let ecdh_es = wallet
        .seal_ecdh_es(
            &request,
            ContentEncryption::A128Gcm,
            &SealOptions::default(),
        )
        .expect("ECDH-ES seal to the advertised P-256 key");
    let reply = wallet
        .post_response(&request.response_uri, &ecdh_es)
        .await
        .expect("answer");
    assert_eq!(reply.status, BAD_REQUEST);
    let records = hardened.evidence().take();
    assert!(matches!(records[0].rejection, Some(Rejection::JweParse(_))));
    assert_eq!(
        wallet
            .session_state(&session.result_uri)
            .await
            .expect("state"),
        Some("pending".to_owned())
    );
    hardened.shutdown().await;
}

/// Conformance mode serves the unique route only: the shared and ECDH-ES research routes are
/// 404, and the research session knobs (`shared`, `ecdh_es_shared`, fixed `nonce` / `state`)
/// are refused at creation.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn conformance_mode_serves_no_shared_or_research_routes() {
    let lab = Lab::start(config(Prefix::SanDns)).await;
    let base = lab.server.base_url();
    for segment in ["shared", "ecdh-es"] {
        let reply = lab
            .wallet
            .post_raw(
                &format!("{base}/lab/v1/response/{segment}"),
                "application/x-www-form-urlencoded",
                b"response=x".to_vec(),
            )
            .await
            .expect("answer");
        assert_eq!(reply.status, NOT_FOUND, "{segment}");
    }
    for body in [
        json!({ "route": "shared" }),
        json!({ "route": "ecdh_es_shared" }),
        json!({ "nonce": "fixed-nonce" }),
        json!({ "state": "fixed-state" }),
    ] {
        let reply = lab
            .wallet
            .post_raw(
                &format!("{base}/lab/v1/sessions"),
                "application/json",
                body.to_string().into_bytes(),
            )
            .await
            .expect("answer");
        assert_eq!(reply.status, BAD_REQUEST, "{body}");
    }
}

/// The Wallet side of §5.9.3: a Request Object whose `client_id` is not the one the
/// Authorization Request named is refused, and so is one without `x5c`.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn wallet_refuses_conformance_request_without_x5c_or_for_another_client_id() {
    let lab = Lab::start(config(Prefix::Hash)).await;
    let session = lab.session().await;
    let jwt = String::from_utf8(
        lab.wallet
            .get(&session.request_uri)
            .await
            .expect("get")
            .body,
    )
    .expect("JWS");
    let refused = lab
        .wallet
        .verify_request(&jwt, &manifest("client_id_x509_san_dns"))
        .await;
    assert!(matches!(
        refused,
        Err(WalletError::Rejected(RequestRejection::ClientId))
    ));
    let mut segments: Vec<String> = jwt.split('.').map(str::to_owned).collect();
    let mut header = decode(&segments[JWS_HEADER]);
    header.remove("x5c");
    segments[JWS_HEADER] = URL_SAFE_NO_PAD.encode(Value::Object(header).to_string());
    let refused = lab
        .wallet
        .verify_request(&segments.join("."), &session.client_id)
        .await;
    assert!(matches!(
        refused,
        Err(WalletError::Rejected(RequestRejection::X5c))
    ));
    lab.wallet
        .verify_request(&jwt, &session.client_id)
        .await
        .expect("the original verifies");
}

/// Kill switch and start checks: conformance mode needs its configuration and no other mode
/// takes it; the bind stays loopback; the client id, certificate, key and origin must fit.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn conformance_mode_refuses_to_start_unless_everything_fits() {
    let start = |config| async move { LabServer::start(config).await.err() };

    let mut no_config = config(Prefix::SanDns);
    no_config.conformance = None;
    assert!(matches!(
        start(no_config).await,
        Some(StartError::ConformanceConfig)
    ));

    let mut hardened = config(Prefix::SanDns);
    hardened.mode = Mode::Hardened;
    assert!(matches!(
        start(hardened).await,
        Some(StartError::ConformanceConfig)
    ));

    for ip in [Ipv4Addr::UNSPECIFIED, Ipv4Addr::new(192, 0, 2, 1)] {
        let mut exposed = config(Prefix::SanDns);
        exposed.bind = SocketAddr::from((ip, 0));
        assert!(
            matches!(start(exposed).await, Some(StartError::LoopbackOnly)),
            "{ip}"
        );
    }

    let x509 = |error: X509Error| move |e: Option<StartError>| matches!(e, Some(StartError::X509(got)) if got == error);
    let mut did_key = config(Prefix::SanDns);
    did_key.client_id =
        protocol_model::ClientIdWire::new(lab_server::DEFAULT_CLIENT_ID).expect("id");
    assert!(x509(X509Error::ClientIdPrefix)(start(did_key).await));

    let mut other_dns = config(Prefix::SanDns);
    other_dns.client_id = protocol_model::ClientIdWire::new("x509_san_dns:localhost").expect("id");
    assert!(
        x509(X509Error::SanMismatch)(start(other_dns).await),
        "SAN, but not the origin host"
    );

    let mut wrong_hash = config(Prefix::Hash);
    wrong_hash.client_id = protocol_model::ClientIdWire::new(format!(
        "x509_hash:{}",
        URL_SAFE_NO_PAD.encode([0u8; 32])
    ))
    .expect("id");
    assert!(x509(X509Error::HashMismatch)(start(wrong_hash).await));

    let mut wrong_key = config(Prefix::SanDns);
    wrong_key.request_signing_key = RequestSigningKey::from_jwk(SPRUCE_JWK).expect("key");
    assert!(x509(X509Error::KeyMismatch)(start(wrong_key).await));

    let mut foreign_origin = config(Prefix::SanDns);
    if let Some(conformance) = &mut foreign_origin.conformance {
        conformance.public_origin =
            PublicOrigin::parse("https://verifier.lab.invalid").expect("origin");
    }
    assert!(x509(X509Error::OriginNotInCertificate)(
        start(foreign_origin).await
    ));

    let mut self_signed = config(Prefix::Hash);
    if let Some(conformance) = &mut self_signed.conformance {
        // The CA certificate as "leaf", anchored at the leaf: self-signed is refused first.
        conformance.credentials =
            X509Credentials::from_pem(CA_PEM, LEAF_KEY_PEM, LEAF_PEM).expect("pem");
    }
    assert!(x509(X509Error::SelfSigned)(start(self_signed).await));

    let mut zero = config(Prefix::SanDns);
    if let Some(conformance) = &mut zero.conformance {
        conformance.max_runtime = Duration::ZERO;
    }
    assert!(matches!(start(zero).await, Some(StartError::ZeroLimit)));

    let mut http_redirect = config(Prefix::SanDns);
    if let Some(conformance) = &mut http_redirect.conformance {
        conformance.response_redirect_uri = Some("http://host.docker.internal/done".to_owned());
    }
    assert!(x509(X509Error::RedirectUri)(start(http_redirect).await));

    let mut fragment = config(Prefix::SanDns);
    fragment.authorization_endpoint = format!("{SUITE_AUTHORIZATION_ENDPOINT}#fragment");
    assert!(matches!(
        start(fragment).await,
        Some(StartError::AuthorizationEndpoint)
    ));

    let chain_with_anchor = [LEAF_PEM, CA_PEM].concat();
    assert_eq!(
        X509Credentials::from_pem(&chain_with_anchor, LEAF_KEY_PEM, CA_PEM).err(),
        Some(X509Error::AnchorInChain)
    );
    assert_eq!(
        X509Credentials::from_pem(b"", LEAF_KEY_PEM, CA_PEM).err(),
        Some(X509Error::ChainLength)
    );
    for origin in [
        "http://host.docker.internal",
        "https://127.0.0.1",
        "https://Host.Docker.Internal",
        "https://host.docker.internal/path",
        "https://host.docker.internal:0",
        "https://host.docker.internal:99999",
    ] {
        assert_eq!(
            PublicOrigin::parse(origin).err(),
            Some(X509Error::Origin),
            "{origin}"
        );
    }
}

/// The time box: a server with a short maximum runtime stops accepting by itself, and its
/// `wait` returns.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn conformance_server_stops_at_its_maximum_runtime() {
    let mut cfg = config(Prefix::SanDns);
    if let Some(conformance) = &mut cfg.conformance {
        conformance.max_runtime = SHORT_RUNTIME;
    }
    let server = LabServer::start(cfg).await.expect("server");
    let addr = server.local_addr();
    tokio::time::timeout(RUNTIME_SLACK, server.wait())
        .await
        .expect("the server stops within its runtime plus slack")
        .expect("serve loop ended cleanly");
    assert!(
        tokio::net::TcpStream::connect(addr).await.is_err(),
        "listener closed"
    );
}

/// The binary enters conformance mode only on the explicit flag: `LAB_MODE=conformance` is
/// refused before any file is read.
#[test]
fn binary_refuses_conformance_mode_from_the_environment() {
    let output = std::process::Command::new(env!("CARGO_BIN_EXE_lab-server"))
        .env("LAB_MODE", "conformance")
        .output()
        .expect("binary runs");
    assert!(!output.status.success());
    assert!(
        String::from_utf8_lossy(&output.stderr)
            .contains("conformance mode needs the explicit --mode conformance flag")
    );
}
